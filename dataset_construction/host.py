class LLMBackend:
    """
    Backend that talks to a local OpenAI-compatible server (e.g., your vLLM at
    http://localhost:port/v1) and returns tool_calls parsed from the stream.
    """

    def __init__(
        self,
        model: str = "nvidia/Qwen3.6-35B-A3B-NVFP4",
        server_url: str | None = None,
        api_key: str | None = None,
        default_search_tool: bool = False,
        tokenizer_name_or_path: str | None = None,
    ):
        self.model = model
        self.server_url = server_url or os.getenv("DIRECT_BASE_URL", "http://localhost:port/v1")
        self.api_key = api_key or os.getenv("DIRECT_API_KEY", "EMPTY")
        self.default_search_tool = default_search_tool

        # Reuse a single client (and its underlying httpx connection pool)
        # across every chat() call instead of creating a brand-new one each
        # time, which previously leaked sockets/memory over long runs.
        self.client = AsyncOpenAI(base_url=self.server_url, api_key=self.api_key)

        # Local tokenizer/processor used to count tokens instead of hitting the
        # vLLM server's /tokenize endpoint. Hitting /tokenize once per chat()
        # call (i.e. once per turn, including every tool-calling round trip)
        # is a synchronous HTTP call that was blocking the event loop and
        # adding load to the engine on top of generation traffic, which could
        # contribute to RPC timeouts under high concurrency. Tokenizing
        # locally is CPU-only and avoids the server round trip entirely.
        tokenizer_path = tokenizer_name_or_path or os.getenv("TOKENIZER_NAME_OR_PATH") or self.model
        self.processor = AutoProcessor.from_pretrained(tokenizer_path, trust_remote_code=True)
        # Text-only tokenizer used for the actual token counting; the processor
        # itself is only used to render the chat template (tokenize=False) so
        # that no image is ever decoded/patchified just to count tokens.
        self.tokenizer = getattr(self.processor, "tokenizer", self.processor)

        self._fallback_tools = [
        ]

    async def aclose(self):
        """Close the underlying HTTP client/connection pool."""
        await self.client.close()
    
    @staticmethod
    def _normalize_messages_for_template(msg: List[Dict[str, Any]]) -> tuple[List[Dict[str, Any]], int]:
        """
        Build a lightweight, image-free copy of the conversation for token
        counting, and return it together with the number of tokens the removed
        images would contribute.

        The processor's chat template implementation always iterates
        message["content"] expecting a list of content-part dicts (e.g.
        {"type": "text", "text": ...}). Several messages in this codebase
        (system prompt, assistant text-only turns, tool results) use a plain
        string for "content" instead, which breaks that iteration (it ends up
        iterating over individual characters). Normalize any string content
        into the list-of-parts form before handing messages to the template.

        Every "image_url" part is DROPPED here and replaced by an analytic
        token estimate (`_estimate_image_tokens`). Feeding the real images to
        the processor would decode each of them into a float32 patch tensor on
        every single turn, which dominates the process's memory usage; only the
        token count matters for `adjust_max_length`.

        Messages that need modification are shallow-copied (never deep-copied):
        with images removed there is no multimodal content left for the
        template to rewrite in place, so copying the base64 payloads or the
        whole growing history every turn is unnecessary.

        Assistant tool_calls also store `function.arguments` as a JSON string
        (the OpenAI wire format, produced by streaming the model's raw text).
        The local chat template's Jinja code expects `arguments` to already be
        a mapping (it iterates it with `|items`), so it is parsed into a dict
        here as well, purely for token counting.
        """
        normalized: List[Dict[str, Any]] = []
        image_tokens = 0
        for message in msg:
            content = message.get("content")
            tool_calls = message.get("tool_calls")
            new_message = dict(message)

            if isinstance(content, str):
                new_message["content"] = [{"type": "text", "text": content}]
            elif isinstance(content, list):
                parts = []
                for part in content:
                    if isinstance(part, dict) and part.get("type") == "image_url":
                        url = (part.get("image_url") or {}).get("url", "")
                        image_tokens += _estimate_image_tokens(url)
                        continue
                    parts.append(part)
                new_message["content"] = parts

            if tool_calls:
                new_tool_calls = []
                for tool_call in tool_calls:
                    new_tool_call = dict(tool_call)
                    function = new_tool_call.get("function")
                    if isinstance(function, dict):
                        function = dict(function)
                        arguments = function.get("arguments")
                        if isinstance(arguments, str):
                            try:
                                function["arguments"] = json.loads(arguments)
                            except (json.JSONDecodeError, ValueError):
                                try:
                                    function["arguments"] = ast.literal_eval(arguments)
                                except (SyntaxError, ValueError):
                                    pass
                        new_tool_call["function"] = function
                    new_tool_calls.append(new_tool_call)
                new_message["tool_calls"] = new_tool_calls

            normalized.append(new_message)
        return normalized, image_tokens

    def _count_tokens(self, msg: List[Dict[str, Any]], tools_schema) -> int:
        """
        Count the number of tokens the chat template would produce for the
        given messages/tools, mirroring what the server's /tokenize endpoint
        would compute but without an HTTP round trip to the vLLM server and
        without ever decoding an image.

        The template is rendered to plain text (tokenize=False) and tokenized
        with the text tokenizer; the vision tokens the dropped images would
        have produced are added back from an analytic estimate.
        """
        normalized, image_tokens = self._normalize_messages_for_template(msg)
        rendered = self.processor.apply_chat_template(
            normalized,
            tools=tools_schema,
            add_generation_prompt=True,
            tokenize=False,
            # apply_chat_template forwards unrecognized kwargs straight into
            # the Jinja template context (and, if unrecognized, on to
            # processor.__call__, which warns about it). "chat_template_kwargs"
            # is a vLLM/OpenAI server-side param name, not something
            # apply_chat_template itself understands; template-only flags like
            # enable_thinking must be passed as top-level kwargs instead.
            enable_thinking=True,
        )
        if isinstance(rendered, (list, tuple)):
            rendered = rendered[0]

        input_ids = self.tokenizer(rendered, add_special_tokens=False)["input_ids"]

        # Unwrap a possible batch dimension (list of lists).
        while isinstance(input_ids, list) and input_ids and isinstance(input_ids[0], list):
            input_ids = input_ids[0]
        return len(input_ids) + image_tokens
    
    async def adjust_max_length(self, messages, max_tokens, tools_schema):
        """
        Adjust the max_length parameter for the model based on the token count of the messages and tools.

        Args:
            messages: List of message dictionaries
            max_tokens: Maximum allowed tokens

        Returns:
            Trimmed list of messages that fit within token limit
        """
        # Tokenization is CPU-bound; run it in a worker thread so it doesn't
        # block the event loop while other concurrent tasks are waiting on I/O.
        total = await asyncio.to_thread(self._count_tokens, messages, tools_schema)

        # If already within limit, return as is
        if total <= max_tokens:
            return max_tokens - total
        else:
            return 0
    
    @retry(
        stop=stop_after_attempt(3),
        wait=wait_exponential(multiplier=1, min=2, max=10),
        reraise=True,
        before_sleep=before_sleep_log(logger, logging.WARNING),
    )
    async def chat(
        self,
        messages: List[Dict[str, Any]],
        tools: List[Dict[str, Any]] | None = None,
        tool_choice: str | None = "auto",
        max_tokens: int = 65536,
    ) -> Dict[str, Any]:

        client = self.client
        max_tokens = await self.adjust_max_length(messages=messages, max_tokens=max_tokens, tools_schema=tools)
        if max_tokens == 0:
            return {"content": None, "reasoning": None, "tool_calls": None, "finish_reason": "context_length_exceeded"}
        payload: Dict[str, Any] = {
            "model": self.model,
            "messages": messages,
            "max_tokens": max_tokens,
            "stream": True,
            "temperature": 1.0,
            "top_p": 0.95,
            "presence_penalty": 1.5,
            "extra_body": {
                "top_k": 20,
                "min_p": 0.0,
                "repetition_penalty": 1.0,
                "chat_template_kwargs": {"preserve_thinking": True}
            }
        }

        if tools and len(tools) > 0:
            payload["tools"] = tools
        elif self.default_search_tool:
            payload["tools"] = self._fallback_tools

        payload["tool_choice"] = tool_choice or "auto"

        stream = await client.chat.completions.create(**payload)

        aggregated_content = ""
        aggregated_reasoning = ""
        tool_call_buffers: Dict[int, Dict[str, Any]] = {}
        finish_reason = None

        try:
            async for chunk in stream:
                choice = chunk.choices[0]
                delta = choice.delta

                if getattr(choice, "finish_reason", None):
                    finish_reason = choice.finish_reason

                if getattr(delta, "content", None): # content outside <thknk> block
                    aggregated_content += delta.content
                    
                if getattr(delta, "reasoning", None): # corresponds to thinking process
                    aggregated_reasoning += delta.reasoning
                    
                if getattr(delta, "tool_calls", None):
                    for tc in delta.tool_calls:
                        idx = getattr(tc, "index", 0) or 0
                        b = tool_call_buffers.setdefault(
                            idx,
                            {"id": None, "type": "function", "function": {"name": "", "arguments": ""}},
                        )
                        if getattr(tc, "id", None):
                            b["id"] = tc.id
                        func = getattr(tc, "function", None)
                        if func is not None:
                            if getattr(func, "name", None):
                                b["function"]["name"] = func.name
                            if getattr(func, "arguments", None):
                                b["function"]["arguments"] += func.arguments
        finally:
            # Explicitly release the streaming response's underlying HTTP
            # connection/buffers instead of relying on GC to eventually call
            # it, which can lag (especially after retried/partial streams)
            # and let connections/memory accumulate over many requests.
            close = getattr(stream, "close", None)
            if close is not None:
                await close()

        tool_calls = list(tool_call_buffers.values()) if tool_call_buffers else None
        content = aggregated_content.strip() if aggregated_content else None
        reasoning = aggregated_reasoning.strip() if aggregated_reasoning else None
        return {"content": content, "reasoning": reasoning, "tool_calls": tool_calls, "finish_reason": finish_reason}
    
