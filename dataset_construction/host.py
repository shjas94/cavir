def _base64_to_pil_and_save(b64_string: str, save_path: str) -> Image.Image:
    """
    Convert a base64-encoded image string to a PIL Image and save it to disk.
    Args:
        b64_string: Base64-encoded image string (with or without data URI prefix)
        save_path: Destination file path to save the image
    Returns:
        The decoded PIL Image
    """
    # Strip optional data URI prefix (e.g. "data:image/png;base64,")
    if "," in b64_string:
        b64_string = b64_string.split(",", 1)[1]
    b64_string = b64_string.strip()
    image_bytes = base64.b64decode(b64_string)
    Path(save_path).parent.mkdir(parents=True, exist_ok=True)
    # Use a context manager so the underlying BytesIO/file resources are
    # released deterministically instead of lingering until GC. Return an
    # in-memory copy so callers still get a usable image after the source
    # buffer is closed.
    with Image.open(BytesIO(image_bytes)) as pil_image:
        pil_image.load()
        pil_image.save(save_path)
        return pil_image.copy()


def _raw_b64(image_ref: str) -> str:
    """
    Return the raw base64 payload from a possibly data-URI-prefixed string.

    image_history stores images as shared "data:image/...;base64,<payload>"
    strings (the same objects referenced by the conversation messages, so each
    image's bytes live in memory only once). The MCP image tools, however,
    expect the raw base64 payload, so this strips the "data:...," prefix when
    resolving an image for a tool call. The stripped string is transient and
    freed once the tool call returns.
    """
    if "," in image_ref:
        return image_ref.split(",", 1)[1]
    return image_ref


def _sanitize_tool_call_arguments(raw_arguments: str) -> str:
    """
    Strip any raw image payload the model may have hallucinated into a tool
    call's arguments before it is persisted into conversation history, so a
    single bad generation doesn't bloat every subsequent turn's context.
    """
    if not raw_arguments:
        return raw_arguments
    try:
        parsed = ast.literal_eval(raw_arguments)
    except (SyntaxError, ValueError):
        return raw_arguments
    if not isinstance(parsed, dict):
        return raw_arguments
    stripped = False
    for key in ("image", "image_base64", "img", "img_b64", "image_data"):
        if key in parsed:
            del parsed[key]
            stripped = True
    if not stripped:
        return raw_arguments
    return json.dumps(parsed)

